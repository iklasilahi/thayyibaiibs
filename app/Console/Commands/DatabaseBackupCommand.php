<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\File;

class DatabaseBackupCommand extends Command
{
    /**
     * The name and signature of the console command.
     *
     * @var string
     */
    protected $signature = 'db:backup {--filename= : Nama file backup khusus}';

    /**
     * The console command description.
     *
     * @var string
     */
    protected $description = 'Backup database ke file SQL di storage/app/backups';

    /**
     * Execute the console command.
     */
    public function handle()
    {
        $this->info('Memulai proses backup database...');

        $backupDir = storage_path('app/backups');
        if (!File::exists($backupDir)) {
            File::makeDirectory($backupDir, 0755, true);
        }

        $connection = config('database.default');
        $databaseName = config("database.connections.{$connection}.database");
        $timestamp = date('Y-m-d_H-i-s');
        $fileName = $this->option('filename') ?: "backup_{$databaseName}_{$timestamp}.sql";
        $filePath = $backupDir . DIRECTORY_SEPARATOR . $fileName;

        try {
            $pdo = DB::connection()->getPdo();
            $tables = DB::connection()->getDoctrineSchemaManager()->listTableNames();
        } catch (\Throwable $e) {
            // Fallback for getting tables in MySQL without doctrine/dbal
            try {
                $tables = array_map(function ($row) {
                    return array_values((array) $row)[0];
                }, DB::select('SHOW TABLES'));
            } catch (\Throwable $ex) {
                $this->error('Gagal mengambil daftar tabel: ' . $ex->getMessage());
                return self::FAILURE;
            }
        }

        try {
            $handle = fopen($filePath, 'w');
            if (!$handle) {
                $this->error("Gagal membuka file tujuan: {$filePath}");
                return self::FAILURE;
            }

            fwrite($handle, "-- Backup Database: {$databaseName}\n");
            fwrite($handle, "-- Tanggal: " . date('Y-m-d H:i:s') . "\n");
            fwrite($handle, "-- Generated by: php artisan db:backup\n\n");
            fwrite($handle, "SET FOREIGN_KEY_CHECKS=0;\n");
            fwrite($handle, "SET SQL_MODE = 'NO_AUTO_VALUE_ON_ZERO';\n\n");

            foreach ($tables as $table) {
                $this->line("Memproses tabel: {$table}...");

                // Struktur tabel
                $createTable = DB::select("SHOW CREATE TABLE `{$table}`");
                if (!empty($createTable)) {
                    $createTableData = (array) $createTable[0];
                    $createSql = $createTableData['Create Table'] ?? array_values($createTableData)[1] ?? '';
                    fwrite($handle, "DROP TABLE IF EXISTS `{$table}`;\n");
                    fwrite($handle, $createSql . ";\n\n");
                }

                // Data tabel
                $rows = DB::table($table)->get();
                if ($rows->count() > 0) {
                    foreach ($rows->chunk(100) as $chunk) {
                        foreach ($chunk as $row) {
                            $rowArray = (array) $row;
                            $columns = array_map(fn($col) => "`{$col}`", array_keys($rowArray));
                            $values = array_map(function ($val) use ($pdo) {
                                if (is_null($val)) {
                                    return 'NULL';
                                }
                                return $pdo->quote((string) $val);
                            }, array_values($rowArray));

                            $insertSql = sprintf(
                                "INSERT INTO `%s` (%s) VALUES (%s);\n",
                                $table,
                                implode(', ', $columns),
                                implode(', ', $values)
                            );
                            fwrite($handle, $insertSql);
                        }
                    }
                    fwrite($handle, "\n");
                }
            }

            fwrite($handle, "SET FOREIGN_KEY_CHECKS=1;\n");
            fclose($handle);

            $fileSize = round(filesize($filePath) / 1024, 2);
            $this->info("Backup database berhasil dibuat!");
            $this->info("Lokasi: {$filePath} ({$fileSize} KB)");

            // Bersihkan backup lama (simpan 10 backup terakhir)
            $this->cleanOldBackups($backupDir, 10);

            return self::SUCCESS;
        } catch (\Throwable $e) {
            $this->error('Terjadi kesalahan saat membackup database: ' . $e->getMessage());
            return self::FAILURE;
        }
    }

    protected function cleanOldBackups(string $dir, int $keepCount)
    {
        $files = File::files($dir);
        if (count($files) > $keepCount) {
            usort($files, fn($a, $b) => $b->getMTime() <=> $a->getMTime());
            $toDelete = array_slice($files, $keepCount);
            foreach ($toDelete as $oldFile) {
                File::delete($oldFile->getPathname());
            }
        }
    }
}
